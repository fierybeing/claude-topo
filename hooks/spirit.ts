// The ASCII spirit. A little wisp wanders the contour map in loose, squiggly loops,
// and the lines it passes turn into characters: each stretch of line becomes the
// character shaped most like it (- _ ‾ / \\ | = o . , and so on). The ground stays
// bare, so there is no grid. Cell by cell the lines dissolve into type around it, and a long wake
// fades back into lines behind it. The pointer stirs the map the same way.
import {
  shader, picture, buffer, scene, table, vec2, vec3, vec4, int, unsigned, range,
  time, dt, size, pointers, floor, length, smoothstep, mix, max, min, clamp,
  sin, cos, exp, fract, dot, step, atan,
} from 'claude-code/shader'
import type { Buffer, Pixel } from 'claude-code/shader'


const CELL = vec2(8, 11)  // one character cell, in points
const DOT = 1.4           // one font pixel, in points
const REACH = 210         // how far the spirit's touch spreads, in points
const LOOP = 120          // how wide its loops swing, in points
const LINGER = 0.11       // how fast its wake fades: lower = a longer trail
const GROUND = vec3(0.039, 0.039, 0.043)
const EMBER = vec3(0.984, 0.890, 0.839)

function hash(a: vec2, b: number): number {
  return fract(sin(dot(a, vec2(12.9898, 78.233)) + b * 37.719) * 43758.5453)
}

// Drifts across the whole map, swinging through loose loops that never quite repeat.
function spirit(): vec2 {
  const drift = vec2(0.5 + 0.34 * cos(time * 0.037), 0.5 + 0.3 * sin(time * 0.029 + 1.3))
  const a = time * 0.45
  const swing = vec2(
    cos(a) + 0.4 * cos(2.3 * a + 1.0) + 0.18 * sin(4.7 * a),
    sin(a) + 0.35 * sin(1.9 * a + 0.4) + 0.2 * cos(5.3 * a),
  )
  return vec2(drift * size + swing * LOOP)
}

// Its touch at a point: strongest at its heart, with a ragged, shifting edge.
function touch(at: vec2): number {
  const off = vec2(at - spirit())
  const turn = atan(off.y, off.x)
  const edge = REACH * (1 + 0.22 * sin(3 * turn + time * 0.7) + 0.12 * sin(5 * turn - time * 1.1))
  let k = smoothstep(edge, edge * 0.3, length(off))
  for (const q of pointers) {
    k = max(k, smoothstep(140, 25, length(at - q.at)) * (1 - step(0.001, q.gone)))
  }
  return k
}

// The wake: what the spirit touched stays as type, fading slowly.
const wake: Buffer = buffer({ scale: 0.25, filter: 'linear' }, p => {
  const before = wake.sample(p.uv).r
  return vec4(max(before * exp(-dt * LINGER), touch(p.point)), 0, 0, 1)
})

// Read once per size: which character each cell becomes. The cell is cut into the
// same 5x6 dots a character is drawn on, and the character whose shape best overlaps
// the line passing through wins, so a line low in the cell becomes _, a slope /, a
// little ring o. The colour is the line's own.
// <match>
// shape match: each candidate character against the cell, as cosine similarity.
// Generated by tools/match.js from tools/font.js; edit those, not this.
const GLYPHS = table([0, 134217728, 4194432, 31744, 1040187392, 31, 138547332, 35725584, 545523777, 4357248, 32506848, 703136, 368389098, 444416, 132, 71303168, 500889134, 488159232, 272697480, 71573634], 'int')  // " " "." ":" "-" "_" "‾" "|" "/" "\\" "+" "=" "*" "#" "~" "'" "," "@" "o" "(" ")"
function bit(g: number, at: number): number {
  return unsigned((GLYPHS.at(g) >> int(at)) & 1)
}
function match(p: Pixel): vec4 {
  let s0 = vec4(0)
  let s1 = vec4(0)
  let s2 = vec4(0)
  let s3 = vec4(0)
  let peak = vec3(0)
  let mass = 0
  for (const row of range(6)) {
    for (const col of range(5)) {
      let ink = 0
      for (const i of range(3)) {
        for (const j of range(3)) {
          const at = vec2((p.cell + vec2((col + (i + 0.5) / 3) / 5, (row + (j + 0.5) / 3) / 6)) * CELL)
          const c = scene.sample(vec2(at / size))
          const l = max(c.r, max(c.g, c.b))
          ink = max(ink, smoothstep(0.15, 0.35, l))
          peak = vec3(mix(peak, c.rgb, step(max(peak.r, max(peak.g, peak.b)), l)))
        }
      }
      const at = row * 5 + col
      mass += ink
      s0 = vec4(s0 + ink * vec4(bit(1, at), bit(2, at), bit(3, at), bit(4, at)))
      s1 = vec4(s1 + ink * vec4(bit(5, at), bit(6, at), bit(7, at), bit(8, at)))
      s2 = vec4(s2 + ink * vec4(bit(10, at), bit(13, at), bit(14, at), bit(15, at)))
      s3 = vec4(s3 + ink * vec4(bit(17, at), bit(18, at), bit(19, at), 0))
    }
  }
  s0 = vec4(s0 * vec4(1.0000, 0.7071, 0.4472, 0.4472))
  s1 = vec4(s1 * vec4(0.4472, 0.4082, 0.4082, 0.4082))
  s2 = vec4(s2 * vec4(0.3162, 0.4472, 0.7071, 0.7071))
  s3 = vec4(s3 * vec4(0.2530, 0.3674, 0.3674, 0))
  let best = 0
  let glyph = 0
  glyph = mix(glyph, 1, step(best + 0.0001, s0.x))
  best = max(best, s0.x)
  glyph = mix(glyph, 2, step(best + 0.0001, s0.y))
  best = max(best, s0.y)
  glyph = mix(glyph, 3, step(best + 0.0001, s0.z))
  best = max(best, s0.z)
  glyph = mix(glyph, 4, step(best + 0.0001, s0.w))
  best = max(best, s0.w)
  glyph = mix(glyph, 5, step(best + 0.0001, s1.x))
  best = max(best, s1.x)
  glyph = mix(glyph, 6, step(best + 0.0001, s1.y))
  best = max(best, s1.y)
  glyph = mix(glyph, 7, step(best + 0.0001, s1.z))
  best = max(best, s1.z)
  glyph = mix(glyph, 8, step(best + 0.0001, s1.w))
  best = max(best, s1.w)
  glyph = mix(glyph, 10, step(best + 0.0001, s2.x))
  best = max(best, s2.x)
  glyph = mix(glyph, 13, step(best + 0.0001, s2.y))
  best = max(best, s2.y)
  glyph = mix(glyph, 14, step(best + 0.0001, s2.z))
  best = max(best, s2.z)
  glyph = mix(glyph, 15, step(best + 0.0001, s2.w))
  best = max(best, s2.w)
  glyph = mix(glyph, 17, step(best + 0.0001, s3.x))
  best = max(best, s3.x)
  glyph = mix(glyph, 18, step(best + 0.0001, s3.y))
  best = max(best, s3.y)
  glyph = mix(glyph, 19, step(best + 0.0001, s3.z))
  best = max(best, s3.z)
  glyph = glyph * step(0.6, mass)
  return vec4(peak, glyph / 32)
}
// </match>

const cells: Buffer = buffer({ size: [320, 160], filter: 'nearest', once: true }, match)

export default shader({
  fps: 30,
  passes: [
    cells,
    wake,
    picture(p => {
      const map = scene.sample(p.uv)
      const cell = vec2(floor(p.point / CELL))
      const read = cells.at(cell)
      const tick = floor(time * 3)

      // each cell turns at its own moment as the wake rises, so the edge dissolves
      const k = wake.sample(p.uv).r
      const due = 0.12 + hash(cell, 0) * 0.8
      const turned = smoothstep(due, due + 0.06, k)

      // near the heart a few characters loosen into specks, then settle again
      let glyph = floor(read.a * 32 + 0.5)
      const near = touch(p.point)
      const loose = step(hash(cell, tick), near * 0.22) * step(0.5, glyph)
      glyph = mix(glyph, mix(1, mix(2, 15, step(0.5, hash(cell, tick + 5))), step(0.4, hash(cell, tick + 9))), loose)

      // the spirit itself: a small bright wisp
      const d = length(vec2((p.point - spirit()) / CELL))
      const heart = 1 - step(0.75, d)
      const wisp = (1 - step(2.2, d)) * (1 - heart) * step(hash(cell, tick + 7), 0.35)
      glyph = mix(glyph, 16, heart)
      glyph = mix(glyph, 17, wisp)

      // the character's pixel under this point
      const inner = vec2(p.point - cell * CELL - vec2(1, 1.3))
      const gx = floor(inner.x / DOT)
      const gy = floor(inner.y / DOT)
      const inside = step(0, gx) * step(gx, 4) * step(0, gy) * step(gy, 5)
      const bits = GLYPHS.at(glyph)
      const ink = inside * unsigned((bits >> int(clamp(gy, 0, 5) * 5 + clamp(gx, 0, 4))) & 1)

      const tint = mix(read.rgb * 1.1, EMBER, max(heart, wisp * 0.5))
      const type = mix(GROUND, tint, ink)
      return vec4(mix(map.rgb, type, max(turned, max(heart, wisp))), 1)
    }),
  ],
})
