// Writes the shape matcher and the glyph table into hooks/spirit.ts, from tools/font.js.
// Contour lines never cross, so the candidates are characters a single line, a stack of
// lines or a little ring can look like. Usage: node tools/match.js
const fs = require('fs'), path = require('path')
const { order, out } = require('./font.js')
const CANDIDATES = '.:-_‾|/\\=~\',o()'
const cand = [...CANDIDATES].map(c => order.indexOf(c))
// a ring or a bracket only wins when the line really curls
const BIAS = { o: 0.8, '(': 0.9, ')': 0.9 }
const weight = g => (BIAS[order[g]] ?? 1) / Math.sqrt(pop(out[g]))
const pop = v => { let n = 0; for (let i = 0; i < 30; i++) n += (v >> i) & 1; return n }
const lanes = 'xyzw', groups = []
for (let i = 0; i < cand.length; i += 4) groups.push(cand.slice(i, i + 4))
const L = []
L.push('// shape match: each candidate character against the cell, as cosine similarity.')
L.push('// Generated by tools/match.js from tools/font.js; edit those, not this.')
L.push(`const GLYPHS = table([${out.join(', ')}], 'int')  // ${order.map(c => JSON.stringify(c)).join(' ')}`)
L.push('function bit(g: number, at: number): number {\n  return unsigned((GLYPHS.at(g) >> int(at)) & 1)\n}')
L.push('function match(p: Pixel): vec4 {')
groups.forEach((g, k) => L.push(`  let s${k} = vec4(0)`))
L.push('  let peak = vec3(0)\n  let mass = 0')
L.push('  for (const row of range(6)) {\n    for (const col of range(5)) {\n      let ink = 0')
L.push('      for (const i of range(3)) {\n        for (const j of range(3)) {')
L.push('          const at = vec2((p.cell + vec2((col + (i + 0.5) / 3) / 5, (row + (j + 0.5) / 3) / 6)) * CELL)')
L.push('          const c = scene.sample(vec2(at / size))\n          const l = max(c.r, max(c.g, c.b))')
L.push('          ink = max(ink, smoothstep(0.15, 0.35, l))\n          peak = vec3(mix(peak, c.rgb, step(max(peak.r, max(peak.g, peak.b)), l)))\n        }\n      }')
L.push('      const at = row * 5 + col\n      mass += ink')
groups.forEach((g, k) => L.push(`      s${k} = vec4(s${k} + ink * vec4(${[0, 1, 2, 3].map(n => g[n] !== undefined ? `bit(${g[n]}, at)` : '0').join(', ')}))`))
L.push('    }\n  }')
groups.forEach((g, k) => L.push(`  s${k} = vec4(s${k} * vec4(${[0, 1, 2, 3].map(n => g[n] !== undefined ? weight(g[n]).toFixed(4) : '0').join(', ')}))`))
L.push('  let best = 0\n  let glyph = 0')
groups.forEach((g, k) => g.forEach((gi, n) => L.push(`  glyph = mix(glyph, ${gi}, step(best + 0.0001, s${k}.${lanes[n]}))\n  best = max(best, s${k}.${lanes[n]})`)))
L.push('  glyph = glyph * step(0.6, mass)\n  return vec4(peak, glyph / 32)\n}')
const file = path.join(__dirname, '..', 'hooks', 'spirit.ts'), src = fs.readFileSync(file, 'utf8')
const a = src.indexOf('// <match>\n') + '// <match>\n'.length, b = src.indexOf('// </match>')
fs.writeFileSync(file, src.slice(0, a) + L.join('\n') + '\n' + src.slice(b))
console.log(`${cand.length} candidates written to hooks/spirit.ts`)
