// 5x6 bitmaps, row 0 at top; bit index = row*5 + col
const G = {
 '.':["     ","     ","     ","     ","  #  ","     "],
 ':':["     ","  #  ","     ","     ","  #  ","     "],
 '-':["     ","     ","     ","#### ","     ","     "].map(r=>r),
 '+':["     ","  #  ","  #  ","#####","  #  ","  #  "],
 '*':["     ","# # #"," ### ","#####"," ### ","# # #"],
 '=':["     ","#####","     ","#####","     ","     "],
 '#':[" # # ","#####"," # # "," # # ","#####"," # # "],
 '%':["##  #","## # ","  #  "," #   ","# ## ","#  ##"],
 '@':[" ### ","#   #","# ###","# # #","# ###"," ### "],
 'C':[" ####","#    ","#    ","#    ","#    "," ####"],
 'L':["#    ","#    ","#    ","#    ","#    ","#####"],
 'A':[" ### ","#   #","#   #","#####","#   #","#   #"],
 'U':["#   #","#   #","#   #","#   #","#   #"," ### "],
 'D':["#### ","#   #","#   #","#   #","#   #","#### "],
 'E':["#####","#    ","#### ","#    ","#    ","#####"],
 '$':[" ####","# #  "," ### ","  # #","#### ","  #  "],
 '&':[" ##  ","#  # "," ##  ","# # #","#  # "," ## #"],
 '?':[" ### ","#   #","   # ","  #  ","     ","  #  "],
 '/':["    #","   # ","  #  ","  #  "," #   ","#    "],
 '<':["   # ","  #  "," #   "," #   ","  #  ","   # "],
 '>':[" #   ","  #  ","   # ","   # ","  #  "," #   "],
 '!':["  #  ","  #  ","  #  ","  #  ","     ","  #  "],
 '~':["     ","     "," #  #","# ## ","     ","     "],
}
const order = Object.keys(G)
const out = order.map(c => { let v = 0; G[c].forEach((r, y) => [...r.padEnd(5)].forEach((ch, x) => { if (ch === '#') v |= 1 << (y * 5 + x) })); return v })
console.log(JSON.stringify(order.join('')), JSON.stringify(out))
module.exports = { order, out, G }
