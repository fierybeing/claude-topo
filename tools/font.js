// 5x6 bitmaps for the spirit's characters; bit = row * 5 + column, row 0 at the top.
// Prints the order and the numbers that hooks/spirit.ts holds in GLYPHS.
const G = {
  ' ': ['     ', '     ', '     ', '     ', '     ', '     '],
  '.': ['     ', '     ', '     ', '     ', '     ', '  #  '],
  ':': ['     ', '  #  ', '     ', '     ', '  #  ', '     '],
  '-': ['     ', '     ', '#####', '     ', '     ', '     '],
  '_': ['     ', '     ', '     ', '     ', '     ', '#####'],
  '‾': ['#####', '     ', '     ', '     ', '     ', '     '],
  '|': ['  #  ', '  #  ', '  #  ', '  #  ', '  #  ', '  #  '],
  '/': ['    #', '   # ', '   # ', ' #   ', ' #   ', '#    '],
  '\\': ['#    ', ' #   ', ' #   ', '   # ', '   # ', '    #'],
  '+': ['     ', '  #  ', '#####', '  #  ', '  #  ', '     '],
  '=': ['     ', '#####', '     ', '     ', '#####', '     '],
  '*': ['     ', '# # #', ' ### ', '# # #', '     ', '     '],
  '#': [' # # ', '#####', ' # # ', ' # # ', '#####', ' # # '],
  '~': ['     ', '     ', ' #  #', '# ## ', '     ', '     '],
  "'": ['  #  ', '  #  ', '     ', '     ', '     ', '     '],
  ',': ['     ', '     ', '     ', '     ', '  #  ', ' #   '],
  '@': [' ### ', '#   #', '# ###', '# # #', '# ###', ' ### '],
  'o': ['     ', '     ', ' ### ', '#   #', '#   #', ' ### '],
  '(': ['   # ', '  #  ', ' #   ', ' #   ', '  #  ', '   # '],
  ')': [' #   ', '  #  ', '   # ', '   # ', '  #  ', ' #   '],
}
const order = Object.keys(G)
const out = order.map(c => { let v = 0; G[c].forEach((r, y) => [...r].forEach((ch, x) => { if (ch === '#') v |= 1 << (y * 5 + x) })); return v })
if (require.main === module) console.log(order.join(''), '\n' + JSON.stringify(out))
module.exports = { order, out }
